import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Inlines the legal markdown into a TypeScript module.
 *
 * The OpenNext Cloudflare Worker does not ship files that are only read at
 * runtime via `fs`, so `readFile('content/legal/<doc>.md')` throws ENOENT in
 * production. Generating a module keeps the content in the bundle while the
 * markdown stays the single source of truth in `content/legal`.
 */
const webRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const legalDir = join(webRoot, 'content/legal');
const docs = ['terms', 'privacy', 'dpa', 'cookies'];

/** Serialize to a single-quoted literal that Biome accepts unchanged. */
const toSingleQuoted = (value) =>
  `'${value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t')}'`;

const entries = docs.map((name) => {
  const markdown = readFileSync(join(legalDir, `${name}.md`), 'utf8');
  return `  ${name}: ${toSingleQuoted(markdown)},`;
});

const output = `// Generated by scripts/generate-legal-content.mjs. Do not edit.
export const LEGAL_CONTENT = {
${entries.join('\n')}
} as const;
`;

writeFileSync(join(webRoot, 'lib/legal-content.generated.ts'), output);
console.log(`[legal-content] wrote lib/legal-content.generated.ts (${docs.length} docs)`);
